/**
 * Bins the measured spectra in data/spectra/ into calc/src/spectra.ts, the table the ozone model
 * reads in the browser as well as in Node. `--check` fails if the table is stale.
 *
 * Bins are JPL 2006's ozone bins (about 2 nm in the ultraviolet), merged five at a time above
 * 340 nm, where nothing but ozone's weak visible bands absorbs and the attenuation is small.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "calc/src/spectra.ts");
const H = 6.62607015e-34;
const C = 299792458;

const rows = (file: string) =>
  readFileSync(path.join(ROOT, "data/spectra", file), "utf8")
    .split("\n")
    .map((l) => l.trim().split(/\s+/).map(Number))
    .filter((a) => a.every(Number.isFinite));

/** The mean of a sampled curve over [a, b], integrating the straight lines between samples. */
function mean(pts: number[][], a: number, b: number): number {
  let s = 0;
  let w = 0;
  for (let i = 1; i < pts.length; i++) {
    const [x0, y0] = pts[i - 1] as [number, number];
    const [x1, y1] = pts[i] as [number, number];
    const lo = Math.max(a, x0);
    const hi = Math.min(b, x1);
    if (hi <= lo) continue;
    const f = (x: number) => y0 + ((y1 - y0) * (x - x0)) / (x1 - x0);
    s += ((f(lo) + f(hi)) / 2) * (hi - lo);
    w += hi - lo;
  }
  return w ? s / w : 0;
}

// Ozone: wl, wu, centre, σ(293 to 298 K), σ(218 K), in 1e-20 cm². The stratosphere is cold: 218 K.
const o3 = rows("2006JPL_O3.txt").filter((a) => a.length === 5);
// O₂ Herzberg continuum: nm, σ in 1e-24 cm².
const o2 = rows("O2_yoshino.abs")
  .filter((a) => a.length === 2 && (a[0] as number) > 200)
  .map(([x, y]) => [x as number, (y as number) * 1e-28]);
// Sunlight at 1 AU in photons m⁻² s⁻¹ nm⁻¹: ATLAS-3 (mW m⁻² nm⁻¹) below 400 nm, Neckel and Labs
// (photons cm⁻² s⁻¹ nm⁻¹) above.
const atlas = rows("atlas3_1994_317_a.dat")
  .filter((a) => a.length === 2 && (a[0] as number) > 100)
  .map(([x, y]) => [x as number, ((y as number) * 1e-3 * (x as number) * 1e-9) / (H * C)]);
const neckel = rows("neckel.flx")
  .filter((a) => a.length === 2 && (a[0] as number) > 300)
  .map(([x, y]) => [x as number, (y as number) * 1e4]);

type Bin = [number, number, number, number, number];
const fine: Bin[] = o3.map(([wl, wu, , , s218]) => {
  const lo = wl as number;
  const hi = wu as number;
  const sun = mean(hi <= 400 ? atlas : neckel, lo, hi) * (hi - lo);
  const so2 = lo >= 204.5 && hi <= 241 ? mean(o2, lo, hi) : 0;
  return [lo, hi, sun, so2, (s218 as number) * 1e-24];
});
const bins: Bin[] = [];
for (let i = 0; i < fine.length; ) {
  const b = fine[i] as Bin;
  if (b[0] < 340) {
    bins.push(b);
    i++;
    continue;
  }
  const group = fine.slice(i, i + 5);
  const sun = group.reduce((s, g) => s + g[2], 0);
  const so3 = group.reduce((s, g) => s + g[2] * g[4], 0) / sun;
  bins.push([b[0], (group.at(-1) as Bin)[1], sun, 0, so3]);
  i += group.length;
}

/** A number as Biome writes it: four significant figures, exponent without a plus sign. */
function lit(x: number): string {
  if (x === 0) return "0";
  if (x >= 1 && x < 1e4) return String(Number(x.toPrecision(6)));
  const [m, e] = x.toExponential(3).split("e") as [string, string];
  return `${Number(m)}e${Number(e)}`;
}

const text = `/**
 * Generated by tools/spectra.ts from data/spectra/ (sources in its README). Do not edit.
 *
 * Sunlight at 1 AU and the absorption cross-sections of O₂ (Herzberg continuum) and O₃ (at 218 K).
 * Each row: [from nm, to nm, photons m⁻² s⁻¹ in the bin, σ O₂ in m², σ O₃ in m²].
 */
export const SPECTRUM: readonly (readonly [number, number, number, number, number])[] = [
${bins.map((b) => `  [${b.map(lit).join(", ")}],`).join("\n")}
];
`;

if (process.argv.includes("--check")) {
  const now = readFileSync(OUT, "utf8");
  if (now !== text) {
    console.error("calc/src/spectra.ts is stale: run node tools/spectra.ts");
    process.exit(1);
  }
  console.log(`calc/src/spectra.ts is current (${bins.length} bins).`);
} else {
  writeFileSync(OUT, text);
  console.log(`calc/src/spectra.ts written (${bins.length} bins).`);
}
