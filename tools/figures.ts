/**
 * Writes every figure as a static SVG to figures/svg/<id>.svg, for GitHub and anyone reading the
 * docs outside the site. Each SVG carries the figures' stylesheet, so it follows the reader's light
 * or dark setting. The site draws the same components live; these files are copies.
 *
 *   pnpm figures           write figures/svg/
 *   pnpm figures --check   fail if any SVG is missing or out of date with the model
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { compute } from "@phosphoros/calc";
import { loadContent } from "@phosphoros/calc/content";
import { loadInputs } from "@phosphoros/calc/load";
import { FIGURES } from "@phosphoros/figures";
import { figureCss } from "@phosphoros/figures/theme";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "figures", "svg");
const CHECK = process.argv.includes("--check");

const r = compute(loadInputs());
const content = loadContent();
const css = figureCss();
const stale: string[] = [];
mkdirSync(OUT, { recursive: true });

for (const [id, def] of Object.entries(FIGURES)) {
  const markup = renderToStaticMarkup(createElement(def.Component, def.build({ r, content })));
  const svg = markup.replace(
    /^<svg([^>]*)>/,
    `<svg$1><!-- Generated by tools/figures.ts from ${def.file} and the model. Edit the source, not this file. --><style>${css}</style><rect width="100%" height="100%" rx="12" class="f-surface"/>`,
  );
  const file = path.join(OUT, `${id}.svg`);
  const text = `${svg}\n`;
  if (CHECK) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== text)
      stale.push(path.relative(ROOT, file));
  } else writeFileSync(file, text);
}

// A figure that no longer exists leaves no orphan behind.
for (const f of readdirSync(OUT)) {
  if (f.endsWith(".svg") && !FIGURES[f.slice(0, -4)]) {
    if (CHECK) stale.push(`figures/svg/${f} (no such figure)`);
    else rmSync(path.join(OUT, f));
  }
}

if (stale.length) {
  console.error(`Out of date (run pnpm figures): ${stale.join(", ")}`);
  process.exit(1);
}
console.log(
  CHECK
    ? `figures/svg/ is current (${Object.keys(FIGURES).length} figures).`
    : `Wrote ${Object.keys(FIGURES).length} figures to figures/svg/.`,
);
